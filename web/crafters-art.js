const TIE = { A: "#c9508b", B: "#8e2d5b" };

/// 36 hairs: four styles in nine colours (the long hair's ninth is the original rainbow).
export const HAIRS = [];
for (const [style, mask] of [["Long", "long"], ["Bob", "bob"], ["Bun", "bun"], ["Curly", "curly"]]) {
  HAIR_COLORS.forEach((hc, i) => {
    if (mask === "long" && i === 8) return HAIRS.push({ name: "Rainbow Long", mask, colors: RAINBOW });
    const r = ramp(hc);
    const colors = mask === "long" ? Object.fromEntries(Object.entries(LONG_ROLES).map(([k, v]) => [k, r[v]])) : { ...r, ...(mask === "bun" ? TIE : {}) };
    HAIRS.push({ name: `${style} ${hc[0]}`, mask, colors });
  });
}

