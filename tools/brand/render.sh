#!/bin/bash
# MineWorldCraft / I'M DEGEN brand art: renders every PNG (and logo.svg) from the HTML pages in this folder.
#
#   tools/brand/render.sh                 # web/brand/logo.png, logo-400.png, logo.svg, banner-x.png, banner-opensea.png
#   tools/brand/render.sh preview.png     # ... and a preview sheet (logo circle-cropped at 400/120/48/32/24 px,
#                                         # X header with the real profile picture, OpenSea phone crops)
#
# Needs only Google Chrome (headless). Each page is drawn at 4x and halved down to its exact size in the browser
# (down.html), which gives clean edges with no seams between pixels. lib/degen.js is rebuilt every run from the
# game's own web/degen-skin-art.js and web/degen-skin.js (exports stripped, wrapped as a plain script), so the
# DEGENs in the art are always the collection's real skins and cards.
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
WEB="$ROOT/web"
OUT="$WEB/brand"
CHROME="${CHROME:-/Applications/Google Chrome.app/Contents/MacOS/Google Chrome}"
SS=4
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT
mkdir -p "$OUT"

# --- the DEGEN art, from the game's own modules
{
  echo "// GENERATED by render.sh from web/degen-skin-art.js and web/degen-skin.js. Do not edit; edit those."
  echo "(function () {"
  sed -e 's/^export //' "$WEB/degen-skin-art.js"
  sed -e '/^import {/,/} from /d' -e '/^export {/d' -e 's/^export //' "$WEB/degen-skin.js"
  echo "window.D = { BACKGROUNDS, SKINS, EYES, MOUTHS, CHEEKS, TOPS, BOTTOMS, SHOES, HEADWEAR, ACCESSORIES,"
  echo "  cardSvg, frontSvg, skinPixels, skinColours, PARTS, faceBox };"
  echo "})();"
} > "$HERE/lib/degen.js"

chrome() { "$CHROME" --headless=new --disable-gpu --hide-scrollbars --virtual-time-budget=10000 --allow-file-access-from-files "$@" >/dev/null 2>&1; }
size() { sips -g pixelWidth -g pixelHeight "$1" | awk '/pixel/ {printf "%s ", $2}'; }

# shot PAGE W H OUT [OUT2 W2 H2]: PAGE at SS x, then downsampled to W x H (and optionally also to W2 x H2).
shot() {
  local page="$1" w="$2" h="$3" out="$4" big="$TMP/$(basename "$4" .png)@${SS}x.png"
  chrome --force-device-scale-factor=$SS --window-size="$w,$h" --screenshot="$big" "file://$HERE/$page"
  chrome --force-device-scale-factor=1 --window-size="$w,$h" --screenshot="$out" "file://$HERE/down.html?src=file://$big&w=$w&h=$h"
  echo "$(basename "$out"): $(size "$out")"
  if [ $# -ge 7 ]; then
    chrome --force-device-scale-factor=1 --window-size="$6,$7" --screenshot="$5" "file://$HERE/down.html?src=file://$big&w=$6&h=$7"
    echo "$(basename "$5"): $(size "$5")"
  fi
}

shot logo.html 1000 1000 "$OUT/logo.png" "$OUT/logo-400.png" 400 400
shot banner-x.html 1500 500 "$OUT/banner-x.png"
shot banner-opensea.html 1400 350 "$OUT/banner-opensea.png"

# logo.svg: the very SVG the logo page draws (the PNGs come from the same source)
"$CHROME" --headless=new --disable-gpu --virtual-time-budget=10000 --allow-file-access-from-files --dump-dom "file://$HERE/logo.html" 2>/dev/null \
  | tr '\n' ' ' | LC_ALL=C sed -e 's/.*\(<svg id="s".*<\/svg>\).*/\1/' -e 's/ id="s"//' \
  | { echo '<?xml version="1.0" encoding="UTF-8"?>'; cat; echo; } > "$OUT/logo.svg"
echo "logo.svg: $(wc -c < "$OUT/logo.svg" | tr -d ' ') bytes"

# the preview sheet, if asked for
if [ $# -ge 1 ]; then
  chrome --force-device-scale-factor=1 --window-size=1640,1210 --screenshot="$1" "file://$HERE/preview.html"
  echo "preview: $1 $(size "$1")"
fi
